/**
 * จังหวะ "ละครแนวตั้ง" — ตัวเลือกจังหวะการเล่าของโหมดนิยาย (book.fictionPacing = 'shortdrama')
 *
 * ที่มา: ถอดโครงจากละครสั้นจีนพากย์ไทย 10 เรื่อง (เรื่องละ 1.5–2.5 ชั่วโมง) ที่ผู้ใช้ให้ศึกษา
 * สิ่งที่ทุกเรื่องมีร่วมกัน:
 *   - เปิดด้วยวิกฤตที่ตัวเอกไม่ได้เป็นคนผิด ภายใน 2 นาทีแรก แล้วตัวเอกตัดสินใจเด็ดขาดทันที
 *   - ข้อผูกมัดที่ปิดสถานะไว้ (แต่งตามสัญญา แฟนปลอม หนี้บุญคุณ) = ช่องว่างระหว่าง "ที่คนอื่นคิด" กับความจริง
 *   - ตัวตนซ้อน 2–3 ชั้น ผู้ชมรู้ก่อนตัวละคร เปิดทีละชั้นตอนมีคนกำลังดูถูกเรื่องนั้นพอดี
 *   - ถูกดูถูกแล้วได้คืนภายในฉากเดียวกัน (1–5 นาที) มีปมใหม่ทุก 2–5 นาที
 *   - ตัวร้ายเป็นคิว ผลหนักขึ้นเป็นขั้น และมักโดนแผนของตัวเองย้อนกลับ
 *   - พีคในงานใหญ่ต่อหน้าคนทั้งงาน มีของปลอมให้ดีใจผิดก่อนพลิกด้วยหลักฐานชั้นที่สอง
 * เอามาเฉพาะโครงและจังหวะ ห้ามลอกพล็อต ชื่อ หรือบทพูดของเรื่องต้นทาง
 *
 * ค่าเริ่มต้นคือ 'classic' — ทุกฟังก์ชันคืน '' แล้ว prompt เหมือนไม่มีฟีเจอร์นี้ทุกตัวอักษร
 */

export const FICTION_PACINGS = [
  { key: 'classic', label: 'นิยายทั่วไป — จังหวะตามแนวเรื่อง' },
  { key: 'shortdrama', label: 'ละครแนวตั้ง — เปิดแรง ตัวตนลับ ตบหน้าถี่ อ่านติด' },
];

const on = (pacing) => pacing === 'shortdrama';

/** เล่มนี้ใช้จังหวะละครแนวตั้งไหม (เฉพาะโหมดนิยาย) */
export const isShortDrama = (book) => book?.contentMode === 'fiction' && on(book?.fictionPacing);

/** กติกาเต็ม — แนบตอนวางโครงเรื่อง ให้ล็อกลง world_rules / promises */
export function shortDramaOutlineKit(book) {
  if (!isShortDrama(book)) return '';
  return `

จังหวะที่ผู้ใช้เลือก: ละครแนวตั้ง — วางทั้งเล่มด้วยจังหวะนี้ (ใช้โครงเท่านั้น ห้ามลอกพล็อตหรือชื่อจากละครเรื่องใด)
- เปิดในวิกฤต: ฉากแรกของบทที่ 1 เริ่มกลางเหตุการณ์ที่ตัวเอกถูกบีบหรือถูกหักหน้าต่อหน้าคนอื่น โดยตัวเอกไม่ได้เป็นคนผิด แล้วตัวเอกตัดสินใจเด็ดขาดภายในฉากนั้น ห้ามเปิดด้วยการปูประวัติ
- ข้อผูกมัดที่ปิดสถานะ: ภายในบทแรก ๆ มีเหตุผูกตัวเอกกับอีกฝ่าย (สัญญาที่มีเงื่อนไขและวันหมดอายุชัด แฟนปลอม หนี้บุญคุณ ภาระที่ต้องรับผิดชอบร่วมกัน) และสถานะจริงถูกปิดไว้จากคนรอบตัว ช่องว่างระหว่าง "สิ่งที่คนอื่นคิด" กับความจริงคือเครื่องผลิตฉาก
- ตัวตนซ้อน: ตัวเอกหรือคู่มีฐานะ ความสามารถ หรือตัวตนที่ซ่อนอย่างน้อย 2 ชั้น ผู้อ่านรู้ก่อนตัวละครอื่น เปิดทีละชั้นในฉากที่มีคนกำลังดูถูกเรื่องนั้นอยู่พอดี ชั้นใหญ่สุดเก็บไว้เปิดราว 70–85% ของเล่ม ระหว่างทางให้มีฉากเกือบแตก
- วงจรดูถูก→เอาคืน: ทุกบทมีอย่างน้อย 1 รอบ คือตัวร้ายดูถูกหรือใส่ร้ายต่อหน้าคนอื่น → คนในฉากเชื่อตัวร้ายก่อน → ตัวเอกพลิกด้วยสิ่งที่ปูไว้ (หลักฐานที่เตรียมไว้ ความสามารถจริง สถานะที่ซ่อน หรือคู่ที่มายืนข้าง) → ตัวร้ายเสียหน้าและได้ผลในฉากเดียวกันหรือฉากถัดไป ห้ามปล่อยให้ตัวเอกถูกกดข้ามบทโดยไม่ได้คืนอะไรเลย ยกเว้นความแค้นใหญ่หนึ่งเรื่องที่เก็บไว้ระเบิดตอนพีค
- คิวตัวร้าย 3–5 คน จากเล็กไปใหญ่ (เช่น เพื่อนร่วมงานขี้อิจฉา → ญาติที่หวังผลประโยชน์ → คู่แข่งที่ทุกคนคิดว่าเหมาะสมกว่า → ผู้บงการตัวจริง) แต่ละคนมีเหตุผลของตัวเอง ได้ผลหนักขึ้นตามขั้น (เสียหน้า → เสียตำแหน่ง → เสียธุรกิจหรือความสัมพันธ์ → รับโทษตามกฎหมาย) และผลควรย้อนมาจากแผนของเขาเอง
- ตัวเอกมีฤทธิ์: รอบเอาคืนอย่างน้อยครึ่งหนึ่งต้องชนะด้วยการกระทำหรือการเตรียมของตัวเอกเอง คู่หรือผู้มีอำนาจเข้ามาเสริมหรือปิดเกมได้ แต่ห้ามให้ตัวเอกรอคนช่วยทุกครั้ง
- บันไดความสัมพันธ์ (ถ้ามีเส้นรัก): ใกล้ชิดเพราะเหตุจำเป็น → อยู่ร่วมพื้นที่ → หึงจากความเข้าใจผิดเล็ก ๆ ที่คลี่คลายใน 1–2 ฉาก → ปกป้องกันต่อหน้าคนอื่น → จุดต่ำสุดก่อนพีค (แยกทางด้วยความเข้าใจผิดที่มีเหตุผลรองรับ) → ยอมรับความรู้สึกจริง → เปิดตัวต่อสาธารณะ วางว่าแต่ละขั้นอยู่บทไหน
- ตัวละครประจำแนว: ผู้ใหญ่หนึ่งคนที่เป็นตัวเร่งและผู้คุ้มครองตัวเอก (ย่า แม่ หรือผู้อาวุโส) และตัวคลายเครียดหนึ่งคน (ผู้ช่วย เพื่อน) ที่มุกมาจากนิสัยและสถานการณ์
- เดิมพันเป็นตัวเลขหรือสิ่งของ: เงินเท่าไร ตำแหน่งอะไร ทรัพย์สินชิ้นไหน เส้นตายเมื่อไร ไม่ใช่ "รวยมาก" ลอย ๆ
- พีคต่อหน้าสาธารณะ: ฉากพีคอยู่ในงานใหญ่ (งานเลี้ยง วันเกิดผู้ใหญ่ งานบริษัท งานแต่ง) ตัวร้ายหลักได้ใจที่สุดก่อน มีของหรือหลักฐานปลอมให้ดีใจผิด แล้วพลิกด้วยหลักฐานชั้นที่สองที่ปูไว้ ปิดคิวตัวร้ายที่เหลือ ตามด้วยฉากอบอุ่นสั้น ๆ เป็นบทส่งท้าย
- จบทุกบทด้วยตะขอ: ฉากท้ายของทุกบทยกเว้นบทสุดท้ายค้างด้วยภัยใหม่ ความลับที่เกือบแตก หรือคำถามที่ต้องเปิดบทถัดไปเพื่อรู้
- เส้นที่ห้ามข้าม: การวางยา การบังคับแต่ง การขายตัวละคร หรือการลวนลาม เขียนได้เฉพาะเป็นความผิดของตัวร้ายที่ต้องรับผล ห้ามเขียนการบังคับหรือการไม่ยินยอมให้เป็นความโรแมนติก ฉากใกล้ชิดของคู่หลักต้องยินยอมทั้งสองฝ่าย ความหึงห้ามกลายเป็นการควบคุมหรือทำร้าย และฝ่ายดีลงโทษตัวร้ายด้วยวิธีที่อยู่ในกฎหมายและสังคม (ไล่ออก ฟ้อง ตัดความร่วมมือ เปิดโปง) ไม่ใช่ทำร้ายร่างกาย
- จดใน world_rules: ตัวตนซ้อนทุกชั้นพร้อมบทที่จะเปิด และคิวตัวร้ายพร้อมบทที่แต่ละคนได้ผล ใส่ใน chapters[].promises ของบทที่ปู`;
}

/** ฉบับย่อ แนบทุกเทิร์นตอนเขียน/แก้ฉาก — ต้องสั้น */
export function shortDramaSceneKit(book) {
  if (!isShortDrama(book)) return '';
  return `
จังหวะละครแนวตั้ง: ฉากเคลื่อนเร็ว บทพูดสั้นคม มีประโยคเด็ดหนึ่งประโยคตอนพลิก · ถ้าฉากนี้มีการดูถูกหรือใส่ร้าย ให้ตัวเอกพลิกคืนด้วยสิ่งที่ปูไว้ในฉากนี้ หรือค้างเป็นตะขอให้ฉากถัดไปคืน · เขียนปฏิกิริยาของคนรอบข้างที่เป็นพยาน (ตกใจ กระซิบ หน้าเปลี่ยน) · ฉากพักจังหวะใช้มุกหรือความหวานแทนการครุ่นคิดยาว · ห้ามเฉลยตัวตนซ้อนก่อนบทที่วางไว้ · การบังคับหรือวางยาเป็นความผิดของตัวร้ายเสมอ ไม่ใช่ความโรแมนติก`;
}

/** ข้อตรวจเพิ่มของบรรณาธิการ */
export function shortDramaReviewCheck(book) {
  if (!isShortDrama(book)) return '';
  return '9. จังหวะละครแนวตั้ง: บทนี้ขาดรอบดูถูก→เอาคืน ตัวเอกถูกกดโดยไม่ได้คืนนานเกินไป เฉลยตัวตนซ้อนก่อนกำหนด ฉากท้ายบทไม่มีตะขอ หรือการบังคับ/ไม่ยินยอมถูกเขียนให้ดูโรแมนติกหรือไม่ (type: setup_payoff)';
}

/** ขั้นตั้งชื่อ/เสนอทิศทาง (ยังไม่มีเล่ม) */
export function shortDramaIdeaNote(contentMode, pacing) {
  if (contentMode !== 'fiction' || !on(pacing)) return '';
  return `\nจังหวะที่ผู้ใช้เลือก: ละครแนวตั้ง — เปิดด้วยวิกฤต ข้อผูกมัดที่ปิดสถานะ ตัวตนซ้อน ถูกดูถูกแล้วเอาคืนถี่ ๆ และพีคต่อหน้าสาธารณะ ทุกตัวเลือกต้องเห็นแรงดึงนี้ตั้งแต่แวบแรก`;
}
