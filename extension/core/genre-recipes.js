const recipeOf = (genre) => (genre && Object.hasOwn(GENRE_RECIPES, genre) ? GENRE_RECIPES[genre] : null);
const find = (list, key) => (list || []).find((x) => x.key === key) || null;

/** แนวนี้มีสูตรให้เลือกไหม (จีนโบราณมีโมดูลของตัวเอง จึงไม่อยู่ที่นี่) */
export const hasGenreRecipe = (genre) => !!recipeOf(genre);

/** เก็บเฉพาะค่าที่มีจริงในแนวนั้น · ไม้เด็ดไม่ซ้ำ ไม่เกินเพดาน · ค่าว่าง = ให้ AI เลือก */
export function normalizeGenreStory(genre, s = {}) {
  const r = recipeOf(genre);
  const out = { genre: r ? genre : '', sub: '', setting: '', tropes: [], mood: '' };
  if (!r || !s || typeof s !== 'object') return out;
  for (const { key } of GENRE_LAYERS) if (find(r[key], s[key])) out[key] = s[key];
  const tropes = Array.isArray(s.tropes) ? s.tropes : [];
  out.tropes = [...new Set(tropes)].filter((k) => find(r.tropes, k)).slice(0, GENRE_MAX_TROPES);
  return out;
}

/** ผู้ใช้เลือกอะไรไว้บ้างไหม — ถ้าไม่ prompt ต้องเหมือนเดิมทุกตัวอักษร */
export function genreStoryPicked(genre, s) {
  const n = normalizeGenreStory(genre, s);
  return !!(n.sub || n.setting || n.mood || n.tropes.length);
}

export function randomGenrePopular(genre, rand = Math.random) {
  const list = recipeOf(genre)?.popular || [];
  if (!list.length) return null;
  const p = list[Math.floor(rand() * list.length) % list.length];
  return { ...normalizeGenreStory(genre, p), name: p.name };
}

/** สูตรที่อ่านเป็นภาษาคน (บนหน้าจอและใน prompt) · ไม่ได้เลือกอะไร = '' */
export function genreRecipeText(genre, story) {
  const r = recipeOf(genre);
  const s = normalizeGenreStory(genre, story);
  if (!r || !genreStoryPicked(genre, s)) return '';
  return [
    ...GENRE_LAYERS.map(({ key, label }) => (s[key] ? `${label}: ${find(r[key], s[key]).label}` : '')),
    s.tropes.length ? `ไม้เด็ด: ${s.tropes.map((k) => find(r.tropes, k).label).join(', ')}` : '',
  ].filter(Boolean).join(' · ');
}

/** กติกาเต็มของทุกตัวเลือก — แนบตอนวางโครงเรื่อง ให้ล็อกลง world_rules */
export function genreOutlineKit(genre, story) {
  const r = recipeOf(genre);
  const s = normalizeGenreStory(genre, story);
  if (!r || !genreStoryPicked(genre, s)) return '';
  const lines = [
    ...GENRE_LAYERS.map(({ key, label }) => (s[key] ? `- ${label} — ${find(r[key], s[key]).label}: ${find(r[key], s[key]).rule}` : '')),
    ...s.tropes.map((k) => `- ไม้เด็ด — ${find(r.tropes, k).label}: ${find(r.tropes, k).rule}`),
  ].filter(Boolean);
  return `

${r.title}ที่ผู้ใช้เลือก (ต้องเห็นชัดในโครงเรื่อง ชั้นที่ไม่ได้เลือกให้เลือกเองให้เข้ากัน)
${lines.join('\n')}
- จดสิ่งที่เลือกไว้ใน world_rules ให้ทุกบทใช้ชุดเดียวกัน และวางว่าไม้เด็ดแต่ละอันโผล่ ถูกใช้ และปิดในบทไหน`;
}

/** ฉบับย่อแนบทุกเทิร์นตอนเขียน/แก้ฉาก */
export function genreSceneKit(genre, story) {
  const r = recipeOf(genre);
  const s = normalizeGenreStory(genre, story);
  if (!r || !genreStoryPicked(genre, s)) return '';
  const mood = s.mood ? `\n- อารมณ์: ${find(r.mood, s.mood).rule}` : '';
  return `
สูตรเรื่องที่ผู้ใช้เลือก: ${genreRecipeText(genre, s)} — ฉากนี้ต้องยังอยู่ในสูตรนี้${mood}`;
}

/** ขั้นตั้งชื่อ/เสนอทิศทาง (ยังไม่มีเล่ม) */
export function genreIdeaNote(genre, story) {
  const text = genreRecipeText(genre, story);
  return text ? `\nสูตรเรื่องที่ผู้ใช้เลือก: ${text}\nทุกตัวเลือกต้องเข้ากับสูตรนี้ ชั้นที่ไม่ได้เลือกให้คิดให้เข้ากัน` : '';
}

/** ข้อตรวจเพิ่มของบรรณาธิการ (เฉพาะเมื่อมีสูตร) */
export function genreReviewCheck(genre, story) {
  const text = genreRecipeText(genre, story);
  return text ? `8. ตรงสูตรที่ผู้ใช้เลือก (${text}): ฉากหลุดอารมณ์หรือแนวย่อย หรือไม้เด็ดที่วางไว้ถูกลืม/ใช้ผิดกติกาหรือไม่ (type: setup_payoff)` : '';
}
