const byKey = (list, key) => list.find((x) => x.key === key);

/** ค่าที่มาจากหน้าจอหรือเล่มเก่าอาจขาด/เพี้ยน — ทำให้เป็นสูตรที่ใช้ได้เสมอ */
export function normalizeChineseStory(s = {}) {
  const src = s && typeof s === 'object' ? s : {};
  const pick = (list, key, d) => (byKey(list, key) ? key : d);
  const many = (list, keys, max) => [...new Set((Array.isArray(keys) ? keys : []).filter((k) => byKey(list, k)))].slice(0, max);
  const arenas = many(CN_ARENAS, src.arenas, CN_MAX_ARENAS);
  return {
    world: pick(CN_WORLDS, src.world, 'fictional'),
    entry: pick(CN_ENTRIES, src.entry, 'transmigrate'),
    arenas: arenas.length ? arenas : ['mansion'],
    tropes: many(CN_TROPES, src.tropes, CN_MAX_TROPES),
    mood: pick(CN_MOODS, src.mood, 'sweet'),
  };
}

/** สุ่มหนึ่งชุดจาก CN_POPULAR · rand ส่งเข้ามาได้เพื่อให้เทสต์คุมผลได้ */
export function randomPopular(rand = Math.random) {
  const r = CN_POPULAR[Math.floor(rand() * CN_POPULAR.length) % CN_POPULAR.length];
  return { ...normalizeChineseStory(r), name: r.name };
}

/** สูตรที่อ่านเป็นภาษาคน — ใช้ทั้งบนหน้าจอและใน prompt */
export function chineseRecipeText(story) {
  const s = normalizeChineseStory(story);
  const tropes = s.tropes.map((k) => byKey(CN_TROPES, k).label);
  return [
    `โลก: ${byKey(CN_WORLDS, s.world).label}`,
    `ประตูเข้าเรื่อง: ${byKey(CN_ENTRIES, s.entry).label}`,
    `สนามหลัก: ${s.arenas.map((k) => byKey(CN_ARENAS, k).label).join(' + ')}`,
    tropes.length ? `ไม้เด็ด: ${tropes.join(', ')}` : '',
    `อารมณ์: ${byKey(CN_MOODS, s.mood).label}`,
  ].filter(Boolean).join(' · ');
}

/**
 * คู่ที่ผสมกันได้แต่ต้องคุม — แสดงบนหน้าจอให้ผู้ใช้รู้ และส่งเข้า prompt เป็นวิธีแก้
 * ไม่ห้ามเลือก เพราะนิยายดี ๆ หลายเรื่องก็ผสมของที่ชนกันแล้วคุมได้
 */
export function chineseClashes(story) {
  const s = normalizeChineseStory(story);
  const has = (k) => s.arenas.includes(k) || s.tropes.includes(k) || s.world === k || s.entry === k || s.mood === k;
  const out = [];
  if (has('farming') && has('palace'))
    out.push('ทำไร่ทำนา (อบอุ่น) กับวังหลัง (เลือดเย็น) อารมณ์คนละขั้ว — ให้ช่วงแรกอยู่ที่หมู่บ้าน แล้ววังหลังเข้ามาเป็นภัยหรือฉากหลังช่วงหลัง ไม่สลับไปมาทุกบท');
  if (has('space') && (has('jianghu') || has('war')))
    out.push('มิติพกพาในเรื่องที่ต้องสู้ เสี่ยงทำให้ตัวเอกเก่งเกินจนไม่ลุ้น — มิติต้องช่วยด้านเสบียงหรือการรักษา ไม่ใช่ชนะศึกแทน');
  if (has('wuxia') && (has('space') || has('mind')))
    out.push('ยุทธภพกำลังภายในพลังอยู่ในขอบเขตมนุษย์ — ของวิเศษต้องเป็นความลับเดียวของเรื่องและมีกติกาแคบ');
  if (has('comedy') && has('revenge'))
    out.push('แก้แค้นแบบตลก ต้องคุมให้บาดแผลของตัวเอกยังมีน้ำหนัก ไม่ล้อเล่นกับความตาย');
  if (has('angst') && has('mind'))
    out.push('เสียงในใจมักเป็นมุกตลก ในเรื่องดราม่าให้ใช้เป็นการรู้ความจริงที่เจ็บปวดแทน');
  if (['tang', 'song', 'ming', 'qing'].includes(s.world) && has('palace'))
    out.push('ราชวงศ์จริง + วังหลัง — ใช้ฮ่องเต้และสนมที่แต่งขึ้นเอง ห้ามใส่ร้ายบุคคลจริงในประวัติศาสตร์');
  if (s.entry === 'native' && s.tropes.includes('space'))
    out.push('คนในยุคได้มิติพกพา — ต้องมีที่มาในโลกเรื่อง (ของตกทอด หยกวิเศษ) เพราะไม่ได้มาจากการทะลุมิติ');
  return out;
}

